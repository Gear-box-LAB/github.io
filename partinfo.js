function tagPart(obj, key) {
  obj.userData.part = key;
  return obj;
}
// 物から親をたどって、印の付いた部品を探す
function partOf(o) {
  for (; o; o = o.parent) if (o.userData.part) return o;
  return null;
}

// タッチ（クリック）した所の部品の説明を出す。ドラッグ（向きを変える操作）では出さない
function enablePartInfo(canvas, getCamera, getRoot) {
  const ray = new THREE.Raycaster();
  const down = { x: 0, y: 0 };
  canvas.addEventListener('pointerdown', e => { down.x = e.clientX; down.y = e.clientY; });
  canvas.addEventListener('pointerup', e => {
    if (Math.hypot(e.clientX - down.x, e.clientY - down.y) > 6) return;
    const r = canvas.getBoundingClientRect();
    ray.setFromCamera({ x: (e.clientX - r.left) / r.width * 2 - 1, y: -(e.clientY - r.top) / r.height * 2 + 1 }, getCamera());
    const hits = ray.intersectObject(getRoot(), true).filter(h => h.object.visible && partOf(h.object));
    // 透かしている物（車体、シリンダーブロック）より、中の見えている部品を先に選ぶ
    const hit = hits.find(h => !(h.object.material && h.object.material.transparent)) || hits[0];
    showPart(hit ? partOf(hit.object).userData.part : null, e.clientX - r.left, e.clientY - r.top, r);
  });
  document.getElementById('partInfo').addEventListener('click', e => { if (e.target.dataset.close !== undefined) showPart(null); });
}

function showPart(part, x, y, r) {
  const box = document.getElementById('partInfo');
  if (!part) { box.hidden = true; return; }
  const [name, text] = typeof part === 'string' ? PART_INFO[part] || [part, ''] : [part.name, part.text];
  box.innerHTML = `<div class="partHead"><b>${name}</b><button type="button" data-close aria-label="説明を閉じる">×</button></div><p>${text}</p>`;
  box.hidden = false;
  // タッチした所のそばに出す。図からはみ出さないように収める
  const w = box.offsetWidth, h = box.offsetHeight;
  box.style.left = `${Math.min(Math.max(x - w / 2, 8), r.width - w - 8)}px`;
  box.style.top = `${y + 16 + h < r.height ? y + 16 : Math.max(8, y - h - 16)}px`;
}
